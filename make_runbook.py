runbook_content = """# 🚀 Ранбук: Оффлайн-управление подсветкой Ajazz AK820 Max HE

Этот документ описывает результаты реверс-инжиниринга HID-протокола клавиатуры Ajazz AK820 Max HE для работы в оффлайн-режиме (без веб-драйверов).

---

## 📋 1. Спецификация устройства (Hardware ID)

Для работы с клавиатурой через библиотеку `hid` используются следующие параметры:
- **Vendor ID (VID):** `0x0c45`
- **Product ID (PID):** `0x80b1`
- **Интерфейсы:** У клавиатуры 4 HID-интерфейса (`1-9:1.0` — `1-9:1.3`). Для надежности пакет отправляется сразу на все доступные пути.

---

## 📦 2. Структура HID-пакета (35 байт полезной нагрузки)

Пакет передается с ведущим нулевым байтом Report ID (`0x00`), за которым следует полезная нагрузка из 64 байт (хвост добивается нулями).

| Индекс байта | Значение / Пример | Описание |
| :--- | :--- | :--- |
| `0` | `0xaa` | Маркер начала пакета (Header) |
| `1` | `0x23` | Длина пакета (35 байт) |
| `2` | `0x10` | Код команды (Управление подсветкой / Lighting) |
| `3..7` | `0x00` | Служебные заполнители |
| `8` | `1` или `0` | Состояние питания подсветки (`1` = Вкл, `0` = Выкл) |
| `9` | `0xff` | Красный цвет (Red: `0x00` – `0xff`) |
| `10` | `0x00` | Зеленый цвет (Green: `0x00` – `0xff`) |
| `11` | `0x00` | Синий цвет (Blue: `0x00` – `0xff`) |
| `12` | `0xff` | Общая яркость / служебный байт (`0xff` = 100%) |
| `13..16` | `0x00` | Дополнительные параметры |
| `17` | `0x05` | Подтип команды |
| `18` | `0x03` | Дополнительный флаг |
| `19..21` | `0x00` | Нули |
| `22..23` | `0xaa 0x55` | Маркеры конца пакета (Footer) |
| `24..63` | `0x00` | Заполнитель до стандартной длины HID-буфера (64 байта) |
"""

with open("AJAZZ_RUNBOOK.md", "w", encoding="utf-8") as f:
    f.write(runbook_content)

